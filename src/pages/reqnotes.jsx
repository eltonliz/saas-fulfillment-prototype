export const ReqPageContext = React.createContext(null);

/* 手机端（门店APP / 买家端）在机内切页时，把当前页 key 上报给 Shell */
export function useReqPage(key) {
  const set = React.useContext(ReqPageContext);
  React.useEffect(() => {
    if (!set) return;
    set(key);
    return () => set(null);
  }, [set, key]);
}

