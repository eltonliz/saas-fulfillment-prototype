function Sec({ t, children }) {
  return (
    <div style={{ marginTop: 14 }}>
      <div style={{ fontSize: 12.5, fontWeight: 700, color: "#10161d", display: "flex", alignItems: "center", gap: 6 }}>
        <span style={{ width: 3, height: 12, background: "#25c7a5", borderRadius: 2 }} />{t}
      </div>
      <div style={{ marginTop: 6, display: "flex", flexDirection: "column", gap: 5 }}>{children}</div>
    </div>
  );
}

function Li({ children }) {
  return (
    <div style={{ display: "flex", gap: 6, fontSize: 12.5, lineHeight: 1.75, color: "#3c4650" }}>
      <span style={{ color: "#25c7a5", flex: "none" }}>·</span>
      <span>{children}</span>
    </div>
  );
}

export function ReqPanel({ reqKey, width, setWidth, onClose, top = 92 }) {
  const req = REQ_NOTES[reqKey];
  const startDrag = (e) => {
    e.preventDefault();
    const move = (ev) => setWidth(Math.min(760, Math.max(300, window.innerWidth - ev.clientX)));
    const up = () => {
      window.removeEventListener("mousemove", move);
      window.removeEventListener("mouseup", up);
      document.body.style.cursor = "";
      document.body.style.userSelect = "";
    };
    document.body.style.cursor = "col-resize";
    document.body.style.userSelect = "none";
    window.addEventListener("mousemove", move);
    window.addEventListener("mouseup", up);
  };

  return (
    <div style={{ position: "fixed", top, right: 0, bottom: 0, width, background: "#fff", borderLeft: "1px solid #e3e7ea", zIndex: 55, display: "flex", flexDirection: "column", boxShadow: "-8px 0 28px rgba(16,22,29,.07)" }}>
      <div onMouseDown={startDrag} title="拖动调整宽度"
        style={{ position: "absolute", left: -4, top: 0, bottom: 0, width: 9, cursor: "col-resize" }}>
        <span style={{ position: "absolute", left: 3, top: "50%", width: 3, height: 44, marginTop: -22, borderRadius: 2, background: "#dfe5e9" }} />
      </div>

      <div style={{ padding: "11px 16px", borderBottom: "1px solid #eef0f2", display: "flex", alignItems: "center", gap: 8, flex: "none" }}>
        <span style={{ fontSize: 14, fontWeight: 700 }}>需求注释</span>
        {req && <span style={{ fontSize: 12, color: "#25c7a5", background: "#e6f7f2", borderRadius: 10, padding: "2px 10px", whiteSpace: "nowrap", overflow: "hidden", textOverflow: "ellipsis" }}>{req.title}</span>}
        <span onClick={onClose} title="收起面板" style={{ marginLeft: "auto", color: "#9aa4ad", cursor: "pointer", fontSize: 18, lineHeight: 1, flex: "none" }}>×</span>
      </div>

      <div style={{ flex: 1, overflowY: "auto", padding: "2px 16px 28px" }}>
        {!req ? (
          <div style={{ color: "#8a949d", fontSize: 12.5, padding: "24px 0", textAlign: "center" }}>本页暂无需求注释</div>
        ) : (
          <>
            {!!req.rules?.length && <Sec t="业务规则">{req.rules.map((x, i) => <Li key={i}>{x}</Li>)}</Sec>}
            {req.flow && <Sec t="数据流转"><div style={{ fontSize: 12.5, lineHeight: 1.85, color: "#3c4650", background: "#f7f9fa", borderRadius: 6, padding: "8px 10px" }}>{req.flow}</div></Sec>}
            {(!!req.pre?.length || !!req.post?.length) && (
              <Sec t="前后置条件">
                {req.pre?.map((x, i) => <Li key={"pre" + i}>前置：{x}</Li>)}
                {req.post?.map((x, i) => <Li key={"post" + i}>后置：{x}</Li>)}
              </Sec>
            )}
            {!!req.err?.length && <Sec t="异常场景">{req.err.map((x, i) => <Li key={i}>{x}</Li>)}</Sec>}
            {!!req.chain?.length && <Sec t="上下游影响">{req.chain.map((x, i) => <Li key={i}>{x}</Li>)}</Sec>}
            {!!req.kj?.length && <Sec t="口径说明">{req.kj.map((x, i) => <Li key={i}>{x}</Li>)}</Sec>}
          </>
        )}
      </div>
    </div>
  );
}
