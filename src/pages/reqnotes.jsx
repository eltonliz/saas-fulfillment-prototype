const CIRCLED = "①②③④⑤⑥⑦⑧⑨⑩⑪⑫⑬⑭⑮⑯⑰⑱⑲⑳";

/* 最长的几条注释是把 ①②③④ 塞在一段话里，读的人分不清边界。
   统一按编号拆行：引导语（「发货分流：」）单独一行，每条编号各占一行 */
function splitCircled(text) {
  const raw = String(text);
  const parts = raw.split(new RegExp(`(?=[${CIRCLED}])`)).map((x) => x.trim()).filter(Boolean);
  if (parts.length <= 1) return [{ mark: "", text: raw }];
  return parts.map((x) => (CIRCLED.includes(x[0]) ? { mark: x[0], text: x.slice(1).trim() } : { mark: "", text: x }));
}

/* 注释里一直用 **加粗** 标重点，但面板原来按纯文本渲染，屏幕上就是一串星号 */
function Rich({ text }) {
  return String(text).split(/(\*\*[^*]+\*\*)/g).map((x, i) =>
    x.startsWith("**") && x.endsWith("**") ? <b key={i}>{x.slice(2, -2)}</b> : <React.Fragment key={i}>{x}</React.Fragment>);
}

/* 整条只有一个「—」的占位不渲染：空章节直接不出现，省得占版面 */
const realList = (a) => (a || []).filter((x) => x && x.trim() !== "—" && !/^(前置|后置|上游|下游)：—$/.test(x.trim()));

function Sec({ t, children }) {
  return (
    <div style={{ marginTop: 16 }}>
      <div style={{ fontSize: 12.5, fontWeight: 700, color: "#10161d", display: "flex", alignItems: "center", gap: 6 }}>
        <span style={{ width: 3, height: 12, background: "#25c7a5", borderRadius: 2 }} />{t}
      </div>
      <div style={{ marginTop: 7, display: "flex", flexDirection: "column", gap: 8 }}>{children}</div>
    </div>
  );
}

function Li({ n, children }) {
  const lines = splitCircled(children);
  return (
    <div style={{ display: "flex", gap: 7, fontSize: 12.5, lineHeight: 1.75, color: "#3c4650" }}>
      <span style={{ color: "#25c7a5", flex: "none", minWidth: 14, textAlign: "right", fontVariantNumeric: "tabular-nums" }}>{n ? `${n}.` : "·"}</span>
      <span style={{ flex: 1, minWidth: 0 }}>
        {lines.map((ln, i) => (
          <div key={i} style={{ display: "flex", gap: 6, marginTop: i ? 4 : 0 }}>
            {ln.mark && <span style={{ color: "#25c7a5", flex: "none" }}>{ln.mark}</span>}
            <span style={{ flex: 1, minWidth: 0 }}><Rich text={ln.text} /></span>
          </div>
        ))}
      </span>
    </div>
  );
}

export function ReqPanel({ reqKey, width, setWidth, onClose, top = 92 }) {
  const req = REQ_NOTES[reqKey];
  const startDrag = (e) => {
    e.preventDefault();
    const move = (ev) => setWidth(Math.min(760, Math.max(300, window.innerWidth - ev.clientX)));
    const up = () => {
      window.removeEventListener("mousemove", move);
      window.removeEventListener("mouseup", up);
      document.body.style.cursor = "";
      document.body.style.userSelect = "";
    };
    document.body.style.cursor = "col-resize";
    document.body.style.userSelect = "none";
    window.addEventListener("mousemove", move);
    window.addEventListener("mouseup", up);
  };

  return (
    <div style={{ position: "fixed", top, right: 0, bottom: 0, width, background: "#fff", borderLeft: "1px solid #e3e7ea", zIndex: 55, display: "flex", flexDirection: "column", boxShadow: "-8px 0 28px rgba(16,22,29,.07)" }}>
      <div onMouseDown={startDrag} title="拖动调整宽度"
        style={{ position: "absolute", left: -4, top: 0, bottom: 0, width: 9, cursor: "col-resize" }}>
        <span style={{ position: "absolute", left: 3, top: "50%", width: 3, height: 44, marginTop: -22, borderRadius: 2, background: "#dfe5e9" }} />
      </div>

      <div style={{ padding: "11px 16px", borderBottom: "1px solid #eef0f2", display: "flex", alignItems: "center", gap: 8, flex: "none" }}>
        <span style={{ fontSize: 14, fontWeight: 700 }}>需求注释</span>
        {req && <span style={{ fontSize: 12, color: "#25c7a5", background: "#e6f7f2", borderRadius: 10, padding: "2px 10px", whiteSpace: "nowrap", overflow: "hidden", textOverflow: "ellipsis" }}>{req.title}</span>}
        <span onClick={onClose} title="收起面板" style={{ marginLeft: "auto", color: "#9aa4ad", cursor: "pointer", fontSize: 18, lineHeight: 1, flex: "none" }}>×</span>
      </div>

      <div style={{ flex: 1, overflowY: "auto", padding: "2px 16px 28px" }}>
        {!req ? (
          <div style={{ color: "#8a949d", fontSize: 12.5, padding: "24px 0", textAlign: "center" }}>本页暂无需求注释</div>
        ) : (
          <>
            {!!realList(req.rules).length && <Sec t="业务规则">{realList(req.rules).map((x, i) => <Li key={i} n={i + 1}>{x}</Li>)}</Sec>}
            {req.flow && <Sec t="数据流转"><div style={{ fontSize: 12.5, lineHeight: 1.85, color: "#3c4650", background: "#f7f9fa", borderRadius: 6, padding: "8px 10px" }}><Rich text={req.flow} /></div></Sec>}
            {(!!realList(req.pre).length || !!realList(req.post).length) && (
              <Sec t="前后置条件">
                {/* 前置 / 后置共用一个连续序号：两段各自从 1 开始会看成重复编号 */}
                {realList(req.pre).map((x, i) => <Li key={"pre" + i} n={i + 1}>{`前置：${x}`}</Li>)}
                {realList(req.post).map((x, i) => <Li key={"post" + i} n={realList(req.pre).length + i + 1}>{`后置：${x}`}</Li>)}
              </Sec>
            )}
            {!!realList(req.err).length && <Sec t="异常场景">{realList(req.err).map((x, i) => <Li key={i} n={i + 1}>{x}</Li>)}</Sec>}
            {!!realList(req.chain).length && <Sec t="上下游影响">{realList(req.chain).map((x, i) => <Li key={i} n={i + 1}>{x}</Li>)}</Sec>}
            {!!realList(req.kj).length && <Sec t="口径说明">{realList(req.kj).map((x, i) => <Li key={i} n={i + 1}>{x}</Li>)}</Sec>}
          </>
        )}
      </div>
    </div>
  );
}
