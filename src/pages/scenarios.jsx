function Table({ head, rows }) {
  return (
    <div className="tbl-wrap" style={{ marginBottom: 22 }}>
      <table className="tbl-tight">
        <thead><tr>{head.map((h) => <th key={h} style={{ minWidth: 88 }}>{h}</th>)}</tr></thead>
        <tbody>
          {rows.map((r) => (
            <tr key={r[0]}>
              {r.map((c, i) => (
                <td key={i} className={i === 0 ? "tw mono" : ""} style={{ lineHeight: 1.7, verticalAlign: "top" }}>{c || "—"}</td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

