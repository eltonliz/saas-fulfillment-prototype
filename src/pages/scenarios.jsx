function Table({ head, rows }) {
  return (
    <div className="tbl-wrap" style={{ marginBottom: 22 }}>
      <table className="tbl-tight">
        <thead><tr>{head.map((h) => <th key={h} style={{ minWidth: 88 }}>{h}</th>)}</tr></thead>
        <tbody>
          {rows.map((r) => (
            <tr key={r[0]}>
              {r.map((c, i) => (
                <td key={i} className={i === 0 ? "tw mono" : ""} style={{ lineHeight: 1.7, verticalAlign: "top" }}>{c || "—"}</td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

export function ScenarioList() {
  const [tab, setTab] = useState("正向场景");
  const TABS = ["正向场景", "逆向与异常场景"];
  return (
    <div>
      <div className="mtabs" style={{ marginBottom: 14 }}>
        {TABS.map((t) => <button key={t} className={tab === t ? "active" : ""} onClick={() => setTab(t)}>{t}</button>)}
      </div>

      {tab === "正向场景" && <Table head={["编号", "业务场景", "谁来操作", "客户 / 员工要做什么", "系统应该怎么反应", "备注"]} rows={FORWARD} />}
      {tab === "逆向与异常场景" && <Table head={["编号", "异常情况", "什么情况下发生", "系统怎么处理 / 怎么防住", "处理后的结果", "备注"]} rows={REVERSE} />}
    </div>
  );
}
